// margin / collar [mm] for a main d1 and branch d3 [mm]; true: from the Soko table
inline bool dims(double d1,double d3,double& margin,double& collar,double& L,double& L2){
    int n=0;const Row* r=rows(n);const double s=std::sqrt(2.0);
    for(int i=0;i<n;++i)if(std::fabs(r[i].d1-d1)<0.5&&std::fabs(r[i].d3-d3)<0.5){
        L=r[i].L;L2=r[i].L2;margin=(L-d3*s)/2;collar=L2-(d1/2*s+d3/2);return true;}
    margin=collar=fallbackMm();L=2*margin+d3*s;L2=d1/2*s+d3/2+collar;return false;
}
